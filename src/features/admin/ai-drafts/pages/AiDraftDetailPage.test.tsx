import { act, fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { MemoryRouter, Route, Routes } from 'react-router-dom'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { HttpError } from '@/lib/httpClient'
import { draftId, makeDraft } from '../testFixtures'
import type { QuestionDraft } from '../types'
import { AiDraftDetailPage } from './AiDraftDetailPage'

const api = vi.hoisted(() => ({ fetchAiDraft: vi.fn(), approveQuestionDraft: vi.fn(), rejectAiDraft: vi.fn() }))
vi.mock('../api/aiDraftApi', () => api)
vi.mock('../draftFlags', () => ({ QUESTION_DRAFTS_ENABLED: true }))
function show(id = draftId) {
  return render(<MemoryRouter initialEntries={[`/content-author/ai-drafts/${id}`]}><Routes><Route path="/content-author/ai-drafts/:draftId" element={<AiDraftDetailPage />} /></Routes></MemoryRouter>)
}
function deferred<T>() { let resolve!: (value: T) => void; const promise = new Promise<T>((done) => { resolve = done }); return { promise, resolve } }
async function select() {
  fireEvent.click(await screen.findByRole('checkbox', { name: 'Chọn câu 1 để duyệt' }))
  fireEvent.click(screen.getByRole('checkbox', { name: 'Chọn câu 3 để duyệt' }))
}
async function settle() { await act(async () => { await Promise.resolve() }) }
describe('AiDraftDetailPage', () => {
  beforeEach(() => {
    Object.values(api).forEach((mock) => mock.mockReset())
    api.fetchAiDraft.mockResolvedValue(makeDraft())
    api.approveQuestionDraft.mockResolvedValue(makeDraft({ status: 'APPROVED' }))
    api.rejectAiDraft.mockResolvedValue(makeDraft({ status: 'REJECTED' }))
  })
  afterEach(() => vi.useRealTimers())

  it('shows usable questions separately from rejected outputs and approves zero-based item indexes', async () => {
    api.fetchAiDraft.mockResolvedValueOnce(makeDraft()).mockResolvedValue(makeDraft({ status: 'APPROVED' }))
    show()
    await select()
    expect(screen.getAllByRole('checkbox')).toHaveLength(3)
    expect(within(screen.getByRole('region', { name: 'Câu bị loại' })).getByText(/Câu đầu ra 5/)).toBeInTheDocument()
    expect(screen.queryByRole('textbox', { name: /stem|Nội dung câu/ })).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: 'Duyệt các câu đã chọn (2)' }))
    await waitFor(() => expect(api.approveQuestionDraft).toHaveBeenCalledExactlyOnceWith(draftId, { itemIndexes: [0, 2] }))
    await waitFor(() => expect(api.fetchAiDraft).toHaveBeenCalledTimes(2))
    expect(await screen.findByText('Đã duyệt')).toBeInTheDocument()
    expect(screen.getByRole('link', { name: 'Mở Ngân hàng câu hỏi' })).toHaveAttribute('href', '/content-author/questions')
    expect(screen.queryByRole('button', { name: /Duyệt các câu đã chọn/ })).not.toBeInTheDocument()
    expect(api.rejectAiDraft).not.toHaveBeenCalled()
  })
  it('sends the exact rejection note, then reloads the terminal draft', async () => {
    const note = '  Nội dung cần sửa.\nGiữ nguyên ghi chú.  '
    api.fetchAiDraft.mockResolvedValueOnce(makeDraft()).mockResolvedValue(makeDraft({ status: 'REJECTED', reviewNote: note }))
    show()
    const field = await screen.findByLabelText('Ghi chú từ chối (không bắt buộc)')
    fireEvent.change(field, { target: { value: note } })
    fireEvent.click(screen.getByRole('button', { name: 'Từ chối' }))
    await waitFor(() => expect(api.rejectAiDraft).toHaveBeenCalledExactlyOnceWith(draftId, { note }))
    expect(await screen.findByText('Đã từ chối')).toBeInTheDocument()
    expect(screen.getByText(/Ghi chú từ chối:/)).toHaveTextContent('Nội dung cần sửa.')
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(2)
    expect(api.approveQuestionDraft).not.toHaveBeenCalled()
  })
  it.each([400, 429])('keeps selected items and note after a %i review failure', async (status) => {
    api.approveQuestionDraft.mockRejectedValue(new HttpError(status, 'Review failed'))
    show()
    await select()
    fireEvent.change(screen.getByLabelText('Ghi chú từ chối (không bắt buộc)'), { target: { value: 'Unsaved review note' } })
    fireEvent.click(screen.getByRole('button', { name: 'Duyệt các câu đã chọn (2)' }))
    expect(await screen.findByRole('alert')).toHaveTextContent(status === 429 ? 'Bạn đã dùng hết lượt sinh hôm nay' : 'Yêu cầu không hợp lệ. Kiểm tra dữ liệu và trạng thái bản nháp rồi thử lại.')
    expect(screen.getByRole('checkbox', { name: 'Chọn câu 1 để duyệt' })).toBeChecked()
    expect(screen.getByRole('checkbox', { name: 'Chọn câu 3 để duyệt' })).toBeChecked()
    expect(screen.getByLabelText('Ghi chú từ chối (không bắt buộc)')).toHaveValue('Unsaved review note')
    expect(api.approveQuestionDraft).toHaveBeenCalledTimes(1)
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(1)
  })
  it('retains a rejection note and selection after rejection fails', async () => {
    api.rejectAiDraft.mockRejectedValue(new HttpError(503, 'Máy chủ chưa phản hồi'))
    show()
    await select()
    fireEvent.change(screen.getByLabelText('Ghi chú từ chối (không bắt buộc)'), { target: { value: 'Please check this' } })
    fireEvent.click(screen.getByRole('button', { name: 'Từ chối' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Máy chủ chưa phản hồi')
    expect(screen.getByLabelText('Ghi chú từ chối (không bắt buộc)')).toHaveValue('Please check this')
    expect(screen.getByRole('checkbox', { name: 'Chọn câu 3 để duyệt' })).toBeChecked()
    expect(api.rejectAiDraft).toHaveBeenCalledExactlyOnceWith(draftId, { note: 'Please check this' })
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(1)
  })
  it('locks every review action during submission and the following refresh while retaining the snapshot', async () => {
    const write = deferred<QuestionDraft>()
    const refresh = deferred<QuestionDraft>()
    api.approveQuestionDraft.mockReturnValue(write.promise)
    api.fetchAiDraft.mockResolvedValueOnce(makeDraft()).mockReturnValueOnce(refresh.promise)
    show()
    await select()
    fireEvent.click(screen.getByRole('button', { name: 'Duyệt các câu đã chọn (2)' }))
    expect(screen.getByRole('checkbox', { name: 'Chọn câu 1 để duyệt' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Từ chối' })).toBeDisabled()
    expect(screen.getByLabelText('Ghi chú từ chối (không bắt buộc)')).toBeDisabled()
    await act(async () => write.resolve(makeDraft({ status: 'APPROVED' })))
    expect(screen.getByText('Đang cập nhật bản nháp…')).toBeInTheDocument()
    expect(screen.getByText('Question stem 1')).toBeInTheDocument()
    expect(screen.getByRole('checkbox', { name: 'Chọn câu 1 để duyệt' })).toBeDisabled()
    expect(screen.getByRole('button', { name: 'Từ chối' })).toBeDisabled()
    await act(async () => refresh.resolve(makeDraft({ status: 'APPROVED' })))
    expect(screen.getByText('Đã duyệt')).toBeInTheDocument()
    expect(api.approveQuestionDraft).toHaveBeenCalledTimes(1)
  })
  it('polls queued and generating detail until ready and clears its timer on unmount', async () => {
    vi.useFakeTimers()
    api.fetchAiDraft.mockResolvedValueOnce(makeDraft({ status: 'QUEUED', result: null })).mockResolvedValueOnce(makeDraft({ status: 'GENERATING', result: null })).mockResolvedValue(makeDraft())
    const view = show()
    await settle()
    await act(async () => { await vi.advanceTimersByTimeAsync(4999) })
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(1)
    await act(async () => { await vi.advanceTimersByTimeAsync(1) })
    expect(screen.getByText('Đang sinh')).toBeInTheDocument()
    await act(async () => { await vi.advanceTimersByTimeAsync(5000) })
    expect(screen.getByText('Chờ duyệt')).toBeInTheDocument()
    await act(async () => { await vi.advanceTimersByTimeAsync(10000) })
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(3)
    view.unmount()
  })
  it('stops polling on failure and displays the safe failure code label', async () => {
    vi.useFakeTimers()
    api.fetchAiDraft.mockResolvedValueOnce(makeDraft({ status: 'GENERATING', result: null })).mockResolvedValue(makeDraft({ status: 'FAILED', result: null, errorCode: 'NOT_CONFIGURED' }))
    show()
    await settle()
    await act(async () => { await vi.advanceTimersByTimeAsync(5000) })
    expect(screen.getByRole('alert')).toHaveTextContent('Chưa cấu hình mô hình AI')
    expect(screen.getByRole('link', { name: 'Gửi yêu cầu mới' })).toHaveAttribute('href', '/content-author/ai-drafts?new=questions')
    await act(async () => { await vi.advanceTimersByTimeAsync(10000) })
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(2)
    expect(api.approveQuestionDraft).not.toHaveBeenCalled()
  })
  it.each(['APPROVED', 'REJECTED'] as const)('keeps %s drafts read only', async (status) => {
    api.fetchAiDraft.mockResolvedValue(makeDraft({ status, reviewNote: 'Already reviewed' }))
    show()
    expect(await screen.findByRole('checkbox', { name: 'Chọn câu 1 để duyệt' })).toBeDisabled()
    expect(screen.queryByRole('button', { name: /Duyệt các câu đã chọn/ })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Từ chối' })).not.toBeInTheDocument()
    expect(api.approveQuestionDraft).not.toHaveBeenCalled()
    if (status === 'REJECTED') expect(screen.queryByRole('link', { name: 'Mở Ngân hàng câu hỏi' })).not.toBeInTheDocument()
  })
  it('does not fetch an invalid draft ID', () => {
    show('invalid')
    expect(screen.getByRole('alert')).toHaveTextContent('ID bản nháp không hợp lệ')
    expect(api.fetchAiDraft).not.toHaveBeenCalled()
  })
  it('refuses non-question detail responses', async () => {
    api.fetchAiDraft.mockResolvedValue({ ...makeDraft(), kind: 'COURSE' })
    show()
    expect(await screen.findByRole('alert')).toHaveTextContent('Trang này chỉ hỗ trợ bản nháp câu hỏi.')
    expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
    expect(api.approveQuestionDraft).not.toHaveBeenCalled()
  })
  it('rejects malformed question results before exposing review actions', async () => {
    api.fetchAiDraft.mockResolvedValue({ ...makeDraft(), result: { items: [{ stem: 'Missing all other fields' }], rejected: [] } })
    show()
    expect(await screen.findByRole('alert')).toBeInTheDocument()
    expect(screen.queryByRole('checkbox')).not.toBeInTheDocument()
    expect(api.approveQuestionDraft).not.toHaveBeenCalled()
  })
  it('clears polling when an actively generating detail unmounts', async () => {
    vi.useFakeTimers()
    api.fetchAiDraft.mockResolvedValue(makeDraft({ status: 'GENERATING', result: null }))
    const view = show()
    await settle()
    view.unmount()
    await act(async () => { await vi.advanceTimersByTimeAsync(15000) })
    expect(api.fetchAiDraft).toHaveBeenCalledTimes(1)
  })
  it.each([400, 429])('translates an HTTP %i detail load failure', async (status) => {
    api.fetchAiDraft.mockRejectedValue(new HttpError(status, 'Raw server error'))
    show()
    expect(await screen.findByRole('alert')).toHaveTextContent(status === 429 ? 'Bạn đã dùng hết lượt sinh hôm nay' : 'Yêu cầu không hợp lệ. Kiểm tra dữ liệu và trạng thái bản nháp rồi thử lại.')
  })
  it('does not expose review actions when a ready draft has no result', async () => {
    api.fetchAiDraft.mockResolvedValue(makeDraft({ result: null }))
    show()
    expect(await screen.findByRole('alert')).toHaveTextContent('Bản nháp chưa có kết quả hợp lệ để duyệt.')
    expect(screen.queryByRole('button', { name: /Duyệt các câu đã chọn/ })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Từ chối' })).not.toBeInTheDocument()
    expect(api.approveQuestionDraft).not.toHaveBeenCalled()
  })
})
